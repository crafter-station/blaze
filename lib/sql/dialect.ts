/** Quote an identifier only when it needs it, so inserted names stay readable. */
export function quoteIdentifier(engine: SqlEngine, name: string): string {
	const q = DIALECTS[engine].quote;
	const plain = engine === "postgres" ? /^[a-z_][a-z0-9_$]*$/ : /^[A-Za-z_][A-Za-z0-9_$]*$/;
	if (plain.test(name) && !RESERVED.has(name.toLowerCase())) return name;
	return `${q}${name.split(q).join(q + q)}${q}`;
}

/** `schema.table`, omitting the schema when it is the default one. */
export function qualifiedName(
	engine: SqlEngine,
	schema: string,
	table: string,
	defaultSchema: string,
): string {
	const name = quoteIdentifier(engine, table);
	return schema === defaultSchema ? name : `${quoteIdentifier(engine, schema)}.${name}`;
}

