/**
 * Per-engine facts the console needs on the client: which CodeMirror dialect to parse
 * with, which formatter grammar to use, how identifiers are quoted, and the built-in
 * functions worth offering in autocomplete.
 */

export interface DialectInfo {
	label: string;
	/** `@codemirror/lang-sql` dialect export name. */
	codemirror: "PostgreSQL" | "MySQL" | "MariaSQL" | "SQLite";
	/** `sql-formatter` language. */
	formatter: "postgresql" | "mysql" | "mariadb" | "sqlite";
	quote: '"' | "`";
	/** Whether the engine accepts `#` as a line comment. */
	hashComments: boolean;
	/** Postgres-style `$tag$ … $tag$` strings. */
	dollarQuotes: boolean;
	/** Backslash escapes inside string literals (MySQL default sql_mode). */
	backslashEscapes: boolean;
	functions: string[];
}

